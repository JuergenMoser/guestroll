"use client";

import { AlertTriangle, Download } from "lucide-react";
import { useState } from "react";
import { useT } from "@/components/I18nProvider";
import { buttonClass } from "@/components/ui";
import { contrastRatio, isInverted, type QrStyle } from "@/lib/qr/style";

const PNG_SIZES = [512, 1024, 2048, 4096];

interface QrPreviewProps {
  /** Markup from `renderQrSvg`, already built from a validated style. */
  svg: string;
  style: QrStyle;
  url: string;
  downloadBase: string;
  dirty: boolean;
}

export function QrPreview({ svg, style, url, downloadBase, dirty }: QrPreviewProps) {
  const t = useT();
  const [pngSize, setPngSize] = useState(2048);
  const contrast = style.transparent ? 21 : contrastRatio(style.foreground, style.background);

  return (
    <div className="space-y-4">
      <div className="grid place-items-center rounded-xl p-4 [background:repeating-conic-gradient(var(--color-sunken-2)_0_25%,var(--color-sunken)_0_50%)_0_0/20px_20px]">
        {/* Generated by our own renderer from a parsed style: strict colors, escaped text. */}
        <div role="img" aria-label={url} className="w-full max-w-80 [&>svg]:h-auto [&>svg]:w-full" dangerouslySetInnerHTML={{ __html: svg }} />
      </div>

      {(contrast < 3 || isInverted(style)) && (
        <p className="flex gap-2 text-sm text-danger">
          <AlertTriangle className="mt-0.5 size-4 shrink-0" aria-hidden />
          {contrast < 3 ? t("admin.qr.lowContrast") : t("admin.qr.inverted")}
        </p>
      )}

      <div className="space-y-2">
        {dirty && <p className="text-sm text-ink-muted">{t("admin.qr.unsaved")}</p>}
        <div className="flex flex-wrap items-center gap-2">
          <select
            value={pngSize}
            onChange={(e) => setPngSize(Number(e.target.value))}
            aria-label={t("admin.qr.size")}
            className="h-8 rounded-md bg-surface px-2 text-sm ring-1 ring-line-2"
          >
            {PNG_SIZES.map((size) => (
              <option key={size} value={size}>
                {size} px
              </option>
            ))}
          </select>
          <a href={`${downloadBase}?size=${pngSize}&download=1`} className={buttonClass("secondary", "sm")}>
            <Download className="size-4" aria-hidden />
            PNG
          </a>
          <a href={`${downloadBase}?format=svg&download=1`} className={buttonClass("secondary", "sm")}>
            <Download className="size-4" aria-hidden />
            SVG
          </a>
        </div>
      </div>
    </div>
  );
}
